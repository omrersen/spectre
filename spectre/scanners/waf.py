"""WAF/firewall detection scanner: passive header/cookie/body signatures plus one benign active probe."""

from __future__ import annotations

import httpx

from .base import BaseScanner
from ..models import Finding, Severity

USER_AGENT = ("Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
              "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36")
PROBE_UA = "Spectre-WAF-Probe/1.0 (security scanner)"
TIMEOUT = 10.0
BODY_LIMIT = 200_000
#: Statuses that usually mean an edge firewall answered the request.
BLOCK_STATUSES = {403, 406, 418, 419, 429, 451, 503, 999}
#: Body markers of JS/captcha challenges (lowercase).
CHALLENGE_MARKERS = ("just a moment...", "checking your browser before accessing",
                     "enable javascript and cookies to continue", "cf-browser-verification",
                     "challenge-platform", "hcaptcha", "g-recaptcha", "complete the security check")
#: Body markers that identify a WAF-generated block page (lowercase).
BLOCK_BODY = ("web application firewall", "modsecurity", "mod_security", "incapsula",
              "cloudflare", "akamai", "sucuri", "wordfence", "fortiweb", "barracuda",
              "denyall", "reblaze", "request unsuccessful", "requested url was rejected",
              "reference #", "bot detection", "attention required", "request rejected")
REMEDIATIONS = {
    "waf": ("WAF detected - scanning may be limited. Coordinate a scanning window, rate-limit "
            "requests and allow-list the scanner IP/user agent where the WAF supports it."),
    "cache": ("Caching layer detected (not a WAF). Purge the cache when validating content "
              "changes so stale responses are not mistaken for results."),
    "blocking": ("WAF blocking detected - adjust scan timing and payloads, lower concurrency, "
                 "and work with the WAF operator to allow-list legitimate test traffic."),
    "challenge": ("Active challenge detected - scanning may fail. Complete the challenge "
                  "manually or allow-list the scanner before testing; do not attempt to solve "
                  "challenges automatically."),
    "none": ("No WAF detected - the target may be more exposed. Consider putting a "
             "reverse proxy/WAF in front of the application and hardening edge controls."),
}


class WAFScanner(BaseScanner):
    """Detect WAF/CDN/firewall solutions protecting the target site."""

    name = "waf"
    description = "WAF/firewall detection scanner"
    version = "1.0.0"

    #: name -> needles matched against headers/cookies/server/body (all lowercase).
    #: body_markers trigger MEDIUM challenge findings; kind="cache" = CDN/cache, not a WAF.
    SIGNATURES: list[dict] = [
        {"name": "Cloudflare", "headers": ("cf-ray", "cf-cache-status", "cf-request-id", "cf-ew-via"),
         "cookies": ("__cfduid", "__cf_bm", "cf_clearance"), "server": ("cloudflare",),
         "body_markers": ("attention required! | cloudflare", "just a moment...", "/cdn-cgi/",
                          "checking your browser before accessing", "sorry, you have been blocked"),
         "severity": Severity.INFO},
        {"name": "AWS WAF", "headers": ("x-amzn-requestid", "x-aws-waf", "x-amz-cf-id"),
         "cookies": (), "server": (), "body_markers": (), "severity": Severity.INFO},
        {"name": "Akamai", "headers": ("x-akamai-transformed", "x-akamai-request-id", "akamai-grn"),
         "cookies": ("ak_bmsc", "bm_sv", "abck"), "server": (), "body_markers": (),
         "severity": Severity.INFO},
        {"name": "Sucuri", "headers": ("x-sucuri-id", "x-sucuri-cache"), "cookies": ("sucuri",),
         "server": (), "body_markers": ("access denied - sucuri website firewall",
                                        "sucuri website firewall"), "severity": Severity.INFO},
        {"name": "Imperva Incapsula", "headers": ("x-iinfo", "x-cdn"),
         "cookies": ("incap_ses", "visid_incap"), "server": (),
         "body_markers": ("incapsula", "request unsuccessful"), "severity": Severity.INFO},
        {"name": "F5 BIG-IP ASM", "headers": (), "cookies": ("bigipserver", "tscookie"),
         "server": (), "body_markers": ("request unsuccessful",
                                        "the requested url was rejected"), "severity": Severity.INFO},
        {"name": "ModSecurity", "headers": ("mod_security", "x-mod-security"), "cookies": (),
         "server": ("mod_security", "modsecurity"),
         "body_markers": ("this error was generated by mod_security", "modsecurity"),
         "severity": Severity.INFO},
        {"name": "Wordfence", "headers": (), "cookies": ("wordfence",), "server": (),
         "body_markers": ("generated by wordfence", "wordfence"), "severity": Severity.INFO},
        {"name": "FortiWeb", "headers": ("x-fortiweb", "fortiweb"), "cookies": ("fortiweb",),
         "server": (), "body_markers": ("fortiweb",), "severity": Severity.INFO},
        {"name": "Barracuda", "headers": ("barracuda",), "cookies": ("barracuda", "barra_counter"),
         "server": (), "body_markers": ("barracuda web application firewall",),
         "severity": Severity.INFO},
        {"name": "DenyAll", "headers": ("denyall",), "cookies": ("denyall",), "server": (),
         "body_markers": ("denyall",), "severity": Severity.INFO},
        {"name": "Reblaze", "headers": ("reblaze", "x-reblaze"), "cookies": ("reblaze", "rbz_"),
         "server": (), "body_markers": ("reblaze",), "severity": Severity.INFO},
        {"name": "Fastly", "headers": ("x-served-by", "x-timer", "fastly-debug-digest"),
         "cookies": (), "server": (), "body_markers": (), "kind": "cache",
         "severity": Severity.INFO},
        {"name": "Varnish", "headers": ("x-varnish",), "cookies": (), "server": (),
         "body_markers": (), "kind": "cache", "severity": Severity.INFO},
    ]

    # ------------------------------------------------------------------ #
    # Entry point
    # ------------------------------------------------------------------ #
    async def scan(self, target: str) -> list[Finding]:
        """Inspect the target's HTTP surface for WAF fingerprints and blocking."""
        url = self._base_url(target)
        if not url:
            return []
        headers = {"User-Agent": USER_AGENT, "Accept": "*/*"}
        try:
            async with httpx.AsyncClient(timeout=TIMEOUT, follow_redirects=True,
                                         verify=False, headers=headers) as client:
                resp = await self._get(client, url)
                if resp is None:
                    return []  # Connection failure: nothing to inspect
                findings, matched = self._passive(url, resp)
                # Benign SQLi-looking probe with a distinctive user agent.
                probe = await self._get(client, url, params={"id": "1' AND '1'='1"},
                                        headers={"User-Agent": PROBE_UA})
        except (httpx.HTTPError, OSError):
            return []

        main_body, probe_body = self._body(resp), self._body(probe)
        challenged = any(m in main_body or m in probe_body for m in CHALLENGE_MARKERS)
        blocked = (probe is not None and probe.status_code in BLOCK_STATUSES
                   and (matched or any(m in probe_body for m in BLOCK_BODY)))
        if challenged:
            findings.append(self._finding(
                "Active challenge detected", Severity.MEDIUM, url,
                "challenge page served (markers: "
                + ", ".join(m for m in CHALLENGE_MARKERS if m in main_body or m in probe_body)[:120]
                + "); probe status "
                + (str(probe.status_code) if probe is not None else "n/a"),
                REMEDIATIONS["challenge"], {"type": "waf", "category": "challenge"}))
        elif blocked:
            findings.append(self._finding(
                "WAF blocking detected", Severity.MEDIUM, url,
                f"HTTP {probe.status_code} on benign probe /?id=1' AND '1'='1"
                + (f"; markers: {', '.join(m for m in BLOCK_BODY if m in probe_body)[:100]}"
                   if any(m in probe_body for m in BLOCK_BODY) else f"; matched {', '.join(matched)}"),
                REMEDIATIONS["blocking"],
                {"type": "waf", "category": "blocking", "status": probe.status_code}))
        if not findings:
            findings.append(self._finding(
                "No WAF detected", Severity.INFO, url,
                "no WAF headers/cookies/body markers; benign probe returned HTTP "
                + (str(probe.status_code) if probe is not None else "n/a"),
                REMEDIATIONS["none"], {"type": "waf", "category": "none"}))
        return findings

    # ------------------------------------------------------------------ #
    # Detection
    # ------------------------------------------------------------------ #
    def _passive(self, url: str, resp: httpx.Response) -> tuple[list[Finding], list[str]]:
        """Match response headers, cookies, Server header and body against SIGNATURES."""
        header_names = [k.lower() for k in resp.headers]
        server = (resp.headers.get("server") or "").lower()
        cookies = [raw.split("=", 1)[0].strip().lower()
                   for raw in resp.headers.get_list("set-cookie")]
        body = self._body(resp)
        findings: list[Finding] = []
        matched: list[str] = []
        for sig in self.SIGNATURES:
            hits = [f"header {n}" for n in sig["headers"] if any(n in h for h in header_names)]
            hits += [f"cookie {n}" for n in sig["cookies"] if any(n in c for c in cookies)]
            hits += [f"server {n!r}" for n in sig["server"] if n in server]
            hits += [f"body {n!r}" for n in sig["body_markers"] if n in body]
            if not hits:
                continue
            matched.append(sig["name"])
            kind = sig.get("kind", "waf")
            noun = "caching layer" if kind == "cache" else "WAF"
            findings.append(self._finding(
                f"{sig['name']} {noun} detected", sig.get("severity", Severity.INFO), url,
                "; ".join(hits[:6]), REMEDIATIONS["cache" if kind == "cache" else "waf"],
                {"type": "waf", "waf": sig["name"], "kind": kind, "matches": hits}))
        return findings, matched

    # ------------------------------------------------------------------ #
    # Helpers
    # ------------------------------------------------------------------ #
    @staticmethod
    async def _get(client: httpx.AsyncClient, url: str, **kwargs) -> httpx.Response | None:
        """GET ``url``, returning None on transport errors."""
        try:
            return await client.get(url, **kwargs)
        except (httpx.HTTPError, OSError, ValueError):
            return None

    @staticmethod
    def _body(resp: httpx.Response | None) -> str:
        if resp is None:
            return ""
        try:
            return resp.text[:BODY_LIMIT].lower()
        except Exception:
            return ""

    @staticmethod
    def _base_url(target: str) -> str:
        """Return a fetchable URL for ``target`` (scheme added when missing)."""
        target = (target or "").strip()
        if not target:
            return ""
        if "://" not in target:
            target = "https://" + target
        return target.split("#", 1)[0]

    @staticmethod
    def _finding(title: str, severity: Severity, target: str, evidence: str,
                 remediation: str, metadata: dict) -> Finding:
        return Finding(title=title, severity=severity, target=target, evidence=evidence,
                       remediation=remediation, scanner=WAFScanner.name, metadata=metadata)
